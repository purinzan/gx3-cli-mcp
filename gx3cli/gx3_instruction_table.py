# How many 16-bit device words one operand of each type occupies.
_TYPE_WORDS: dict[str, int] = {
    "bit": 1, "word": 1, "int16": 1, "uint16": 1, "bcd4": 1, "device": 1,
    "int32": 2, "uint32": 2, "real32": 2, "dword": 2, "bcd8": 2,
    "real64": 4, "bcd16": 4,
}

# Inclusive value range of the integer types, for range checks on constants.
_TYPE_RANGE: dict[str, tuple[int, int]] = {
    "int16": (-32768, 32767), "uint16": (0, 65535),
    "int32": (-2147483648, 2147483647), "uint32": (0, 4294967295),
}


def manual_write_indices(opcode: str, argc: int) -> set[int] | None:
    """Destination operand positions for opcode at this operand count.

    None when the manuals do not pin it down, so the caller can fall back.
    """
    entry = MANUAL_WRITE_ARGS.get(opcode)
    if entry is None:
        return None
    indices = entry.get(argc)
    if indices is None:
        return None
    return set(indices)


def manual_operand_types(opcode: str, argc: int) -> tuple[str, ...] | None:
    """Type code per operand, or None when the manuals do not pin it down."""
    entry = MANUAL_OPERAND_TYPES.get(opcode)
    if entry is None:
        return None
    return entry.get(argc)


def operand_words(type_code: str) -> int:
    """Device words one operand of this type occupies. 1 when unknown."""
    return _TYPE_WORDS.get(type_code, 1)


def operand_range(type_code: str) -> tuple[int, int] | None:
    """Inclusive value range of an integer type, or None if it is not one."""
    return _TYPE_RANGE.get(type_code)
